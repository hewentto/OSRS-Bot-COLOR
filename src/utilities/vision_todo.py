def wiki_override_url(sprite_filename: str) -> Union[str, None]:
    """
    Returns where to download a sprite from if the OSRS Wiki calls it something else, or None if it doesn't.
    """
    if wiki_file := WIKI_FILE_OVERRIDES.get(sprite_filename):
        return f"https://oldschool.runescape.wiki/images/{quote(wiki_file.replace(' ', '_'))}"
    return None


def fetch_missing_sprites(reports: List[BotReport]) -> None:
    """
    Tries to download each missing sprite from the OSRS Wiki. Names that don't match a Wiki page stay on the checklist.
    """
    import requests

    from utilities.sprite_scraper import SpriteScraper

    missing = sorted({filename for report in reports for filename, _, exists in report.sprites if not exists})
    for filename in [f for f in missing if wiki_override_url(f)]:
        response = requests.get(wiki_override_url(filename), headers={"User-Agent": "OSBC sprite fetcher"}, timeout=20)
        if response.ok and response.content.startswith(b"\x89PNG"):
            ITEM_SPRITES.joinpath(filename).write_bytes(response.content)
            print(f"Success: {filename} saved from {WIKI_FILE_OVERRIDES[filename]}")
        else:
            print(f"Couldn't download {WIKI_FILE_OVERRIDES[filename]} for {filename} (HTTP {response.status_code}).")
    search_terms = [re.sub(r"_\d+$", "", Path(f).stem).replace("_", " ") for f in missing if not wiki_override_url(f)]
    if search_terms:
        SpriteScraper().search_and_download(", ".join(dict.fromkeys(search_terms)), destination=ITEM_SPRITES)


def main() -> None:
    if "--fetch" in sys.argv:
        fetch_missing_sprites(scan_all_bots())
    reports = scan_all_bots()
    try:
        runtime_missing = json.loads(MISSING_SPRITES_LOG.read_text())
    except (FileNotFoundError, json.JSONDecodeError):
        runtime_missing = {}
    # Sprites that have been added since they were reported don't need chasing anymore.
    runtime_missing = {filename: entry for filename, entry in runtime_missing.items() if not ITEM_SPRITES.joinpath(filename).exists()}
    CHECKLIST.write_text(render_markdown(reports, runtime_missing), encoding="utf-8")
    sprites = {sprite for report in reports for sprite in report.sprites}
    print(f"{sum(exists for _, _, exists in sprites)}/{len(sprites)} sprites present. Checklist written to {CHECKLIST}")


if __name__ == "__main__":
    main()
